# Rebuild the embedded image from the editable PNG. Run from any working directory.
[CmdletBinding()]
param()
$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Drawing
$repoRoot = Split-Path $PSScriptRoot -Parent
$pngPath = Join-Path $repoRoot 'assets\buttons\controller-buttons.png'
$headerPath = Join-Path $repoRoot 'RetroInput\Core\ButtonImageData.h'
$image = [System.Drawing.Bitmap]::new($pngPath)
try {
    if ($image.Width -ne 256 -or $image.Height -ne 128) {
        throw 'The current image-pack layout requires a 256x128 PNG with 32x32 tiles.'
    }
    $runs = [System.Collections.Generic.List[string]]::new()
    $last = [uint32]0
    $count = 0
    for ($y = 0; $y -lt $image.Height; $y++) {
        for ($x = 0; $x -lt $image.Width; $x++) {
            $colour = $image.GetPixel($x, $y)
            $pixel = if ($colour.A -eq 0) { [uint32]0 } else {
                [BitConverter]::ToUInt32([BitConverter]::GetBytes($colour.ToArgb()), 0)
            }
            if ($count -gt 0 -and $pixel -ne $last) {
                $runs.Add(('    {{ {0}u, 0x{1:X8}u }},' -f $count, $last))
                $count = 0
            }
            $last = $pixel
            $count++
        }
    }
    $runs.Add(('    {{ {0}u, 0x{1:X8}u }},' -f $count, $last))
    $header = @(
        '#pragma once', '#include <cstdint>',
        '// Generated by tools/PackButtonImages.ps1 from assets/buttons/controller-buttons.png.',
        '// Do not edit these pixels by hand. Repack after editing the source PNG.',
        'namespace RetroInput::Buttons::Data {',
        'inline constexpr int Width = 256, Height = 128, TileSize = 32;',
        'struct Run { unsigned count; std::uint32_t argb; };',
        'inline constexpr Run Runs[] = {'
    ) + $runs.ToArray() + @(
        '};',
        'static_assert([] { unsigned count = 0; for (const auto& run : Runs) count += run.count; return count == Width * Height; }());',
        '} // namespace RetroInput::Buttons::Data'
    )
    [IO.File]::WriteAllText($headerPath, ($header -join "`n") + "`n", [Text.UTF8Encoding]::new($false))
    Write-Output "Packed $($image.Width)x$($image.Height) PNG into $($runs.Count) pixel runs."
} finally {
    $image.Dispose()
}

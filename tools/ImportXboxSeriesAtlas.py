"""Import every supplied Xbox Series icon except white face buttons.

Usage: python tools/ImportXboxSeriesAtlas.py path/to/T_X_Alt_Sprite.png
Requires Pillow. Normal builds embed the resulting PNG directly.
"""
from pathlib import Path
import json
import sys
from PIL import Image

root = Path(__file__).resolve().parent.parent
source = Image.open(sys.argv[1]).convert('RGBA')
if source.size != (179, 512):
    raise ValueError('This map expects the supplied 179x512 sheet')
xs = [0, 47, 95, 142]
ys = [0, 48, 95, 143, 190, 238, 285, 333, 381, 428, 476]
entries = [
    ('South',2,0), ('East',1,0), ('West',3,0), ('North',0,0),
    ('LeftShoulder',0,2), ('RightShoulder',1,2), ('LeftTrigger',2,2), ('RightTrigger',3,2),
    ('DpadUp',0,3), ('DpadDown',1,3), ('DpadLeft',2,3), ('DpadRight',3,3),
    ('DpadLeftRight',2,8), ('Menu',0,10), ('View',1,10),
    ('LeftStick',0,4), ('RightStick',0,6), ('DpadUpDown',1,8),
]
for side, row in [('Left',4), ('Right',6)]:
    for col, suffix in enumerate(['AllDirections','LeftRight','UpDown'], start=1):
        entries.append((side+'Stick'+suffix,col,row))
    for col, suffix in enumerate(['Up','Down','Left','Right']):
        entries.append((side+'Stick'+suffix,col,row+1))
entries += [('DpadNeutral',0,8), ('Share',3,8), ('LeftStickDiagram',0,9),
            ('RightStickDiagram',1,9), ('LeftStickDiagramAlt',2,9), ('RightStickDiagramAlt',3,9)]
assert len(entries) == 38
assert {(col,row) for _,col,row in entries} == {
    (col,row) for row in range(11) for col in range(4)
    if row != 1 and (row < 10 or col < 2)
}
atlas = Image.new('RGBA',(1024,1024))
manifest = []
for index, (name,col,row) in enumerate(entries):
    rect = (xs[col],ys[row],xs[col]+37,ys[row]+37)
    tile = source.crop(rect).resize((120,120),Image.Resampling.LANCZOS)
    atlas.paste(tile,(index%8*128+4,index//8*128+4))
    manifest.append({'button':name,'source_cell':[col,row],'source_rect':rect,'tile':index})
aliases = {'LeftStickClick':'LeftStickDiagram','RightStickClick':'RightStickDiagram',
           'LeftStickClickDiagram':'LeftStickDiagram','RightStickClickDiagram':'RightStickDiagram',
           'LeftStickClickDiagramAlt':'LeftStickDiagramAlt','RightStickClickDiagramAlt':'RightStickDiagramAlt'}
destination = root/'assets/buttons/xbox-series'
destination.mkdir(parents=True,exist_ok=True)
atlas.save(destination/'atlas.png')
(destination/'import-map.json').write_text(json.dumps({'icons':manifest,'aliases':aliases},indent=2)+'\n')
lines = ['#pragma once', '// Generated by tools/ImportXboxSeriesAtlas.py.',
         '// Included inside RetroInput::Buttons; unsupported controls stay -1.',
         'inline constexpr auto XboxSeriesTiles = [] {',
         '    std::array<int, static_cast<unsigned>(Button::Count)> tiles = {};',
         '    tiles.fill(-1);']
tiles = {name:i for i,(name,_,_) in enumerate(entries)}
for name,index in tiles.items():
    lines.append(f'    tiles[static_cast<unsigned>(Button::{name})] = {index};')
for name,target in aliases.items():
    lines.append(f'    tiles[static_cast<unsigned>(Button::{name})] = {tiles[target]};')
lines += ['    return tiles;','}();']
(root/'RetroInput/Core/XboxSeriesImageMap.h').write_text('\n'.join(lines)+'\n')
print('Imported 38 Xbox Series icons; white face buttons excluded; 128px tiles')

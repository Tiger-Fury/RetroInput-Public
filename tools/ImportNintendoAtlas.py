"""Import all 45 icons from the supplied Nintendo Switch sheet.
Usage: python tools/ImportNintendoAtlas.py path/to/T_S_Alt_2_Sprite.png
Requires Pillow. Builds embed the resulting atlas directly.
"""
from pathlib import Path
import json, sys
from PIL import Image
root=Path(__file__).resolve().parent.parent
source=Image.open(sys.argv[1]).convert('RGBA')
if source.size!=(632,1976): raise ValueError('Expected the supplied 632x1976 Nintendo sheet')
names=[
 'East','South','West','North',
 'DpadRight','DpadDown','DpadLeft','DpadUp',
 'LeftShoulder','LeftRailShoulder','RightShoulder','RightRailShoulder',
 'LeftTrigger','RightTrigger','RightStickUp','LeftStickUpDown',
 'LeftStickAllDirections','RightStick','LeftStick','LeftStickUp',
 'LeftStickLeft','LeftStickDown','LeftStickRight','RightStickLeft',
 'RightStickDown','RightStickUpDown','RightStickAllDirections','RightStickRight',
 'RightStickLeftRight','LeftStickLeftRight','Menu','View',
 'Home','JoyConPairDiagram','JoyConDiagram','JoyConDiagramAlt',
 'DpadNeutral','DpadUpDiagram','DpadLeftDiagram','DpadDownDiagram',
 'DpadUpDown','DpadRightDiagram','DpadLeftRight','Share','JoyConPairDiagramAlt'
]
assert len(names)==45 and len(set(names))==45
aliases={'LeftStickClick':'LeftStick','RightStickClick':'RightStick'}
atlas=Image.new('RGBA',(1024,1024))
icons=[]
for index,name in enumerate(names):
 col,row=index%4,index//4
 rect=(col*168,row*168,col*168+128,row*168+128)
 tile=source.crop(rect).resize((120,120),Image.Resampling.LANCZOS)
 atlas.paste(tile,(index%8*128+4,index//8*128+4))
 icons.append({'button':name,'source_cell':[col,row],'source_rect':rect,'tile':index})
destination=root/'assets/buttons/nintendo'
destination.mkdir(parents=True,exist_ok=True)
atlas.save(destination/'atlas.png')
(destination/'import-map.json').write_text(json.dumps({'icons':icons,'aliases':aliases},indent=2)+'\n')
lines=['#pragma once','// Generated by tools/ImportNintendoAtlas.py.',
 'inline constexpr auto NintendoTiles = [] {',
 '    std::array<int, static_cast<unsigned>(Button::Count)> tiles = {};','    tiles.fill(-1);']
for i,name in enumerate(names): lines.append(f'    tiles[static_cast<unsigned>(Button::{name})] = {i};')
for name,target in aliases.items(): lines.append(f'    tiles[static_cast<unsigned>(Button::{name})] = {names.index(target)};')
lines+=['    return tiles;','}();']
(root/'RetroInput/Core/NintendoImageMap.h').write_text('\n'.join(lines)+'\n')
print('Imported all 45 Nintendo icons into 128px tiles')
